#!/usr/bin/env python3
"""Minimal stand-in for `flutter gen-l10n` used only by the offline analyze harness.
Generates lib/l10n/app_localizations.dart from the ARB files. Real builds use the
Flutter SDK generator; this keeps static analysis honest about key coverage."""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[1]
arb_dir = root / "lib" / "l10n"
out = arb_dir / "app_localizations.dart"

def load(lang):
    return json.loads((arb_dir / ("app_" + lang + ".arb")).read_text(encoding="utf-8"))

en = load("en"); am = load("am")
keys = [k for k in en if not k.startswith("@")]
missing_am = [k for k in keys if k not in am]
if missing_am:
    print("MISSING_AMHARIC_KEYS:", missing_am); sys.exit(1)

def params(msg):
    return sorted(set(re.findall(r"\{(\w+)\}", msg)))

def body(lang_map, k):
    t = lang_map[k]
    interp = re.sub(r"\{(\w+)\}", r"$\1", t)  # placeholder -> $name (Dart interp)
    escaped = interp.replace("'", "\\'").replace("$name","$name")
    return "'" + escaped + "'"

methods = []
for k in keys:
    ps = params(en[k])
    sig = ", ".join("Object " + p for p in ps)
    if not ps:
        m = "  String get " + k + " {\n"
    else:
        m = "  String " + k + "(" + sig + ") {\n"
    m += "    switch (localeName) {\n"
    m += "      case 'am':\n        return " + body(am, k) + ";\n"
    m += "      default:\n        return " + body(en, k) + ";\n"
    m += "    }\n  }"
    methods.append(m)

header = """// GENERATED by tool/gen_l10n.py (offline harness). Real builds regenerate via
// `flutter gen-l10n` from the same ARB sources. Do not edit by hand.
import 'package:flutter/widgets.dart';

class AppLocalizations {
  AppLocalizations(this.localeName);
  final String localeName;

  static const LocalizationsDelegate<AppLocalizations> delegate = _AppLocalizationsDelegate();
  static const List<Locale> supportedLocales = [Locale('en'), Locale('am')];

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;
"""
footer = """
}

class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();
  @override bool isSupported(Locale locale) => ['en','am'].contains(locale.languageCode);
  @override Future<AppLocalizations> load(Locale locale) async => AppLocalizations(locale.languageCode);
  @override bool shouldReload(_AppLocalizationsDelegate old) => false;
}
"""
out.write_text(header + "\n" + "\n".join(methods) + footer, encoding="utf-8")
print("generated", out, len(keys), "keys")
